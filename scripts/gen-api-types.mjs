// Generates TypeScript types from the running service's OpenAPI document.
// Zero dependencies: fetches /openapi.json and renders interfaces with plain
// string building, so the renderer can import request/response shapes and let
// the compiler catch field drift.
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const port = process.env.VOICE_PARTNER_PORT || '3900'
const source = process.argv[2] || `http://127.0.0.1:${port}/openapi.json`
const output = join(root, 'src', 'renderer', 'src', 'lib', 'api-types.ts')

const response = await fetch(source)
if (!response.ok) {
  throw new Error(`Could not read ${source}: HTTP ${response.status}`)
}
const spec = await response.json()
const schemas = spec.components?.schemas ?? {}

function refName(ref) {
  return ref.split('/').pop()
}

function tsType(schema) {
  if (!schema) return 'unknown'
  if (schema.$ref) return refName(schema.$ref)
  if (schema.anyOf) return schema.anyOf.map(tsType).join(' | ')
  if (schema.oneOf) return schema.oneOf.map(tsType).join(' | ')
  if (schema.allOf) return schema.allOf.map(tsType).join(' & ')
  if (schema.enum) return schema.enum.map((value) => JSON.stringify(value)).join(' | ')
  if (Array.isArray(schema.type)) {
    return schema.type.map((type) => tsType({ ...schema, type })).join(' | ')
  }
  if (schema.type === 'string') return 'string'
  if (schema.type === 'integer' || schema.type === 'number') return 'number'
  if (schema.type === 'boolean') return 'boolean'
  if (schema.type === 'null') return 'null'
  if (schema.type === 'array') return `Array<${tsType(schema.items)}>`
  if (schema.type === 'object' || schema.properties) {
    if (schema.properties) {
      const required = new Set(schema.required ?? [])
      const fields = Object.entries(schema.properties).map(([key, value]) => {
        const optional = required.has(key) ? '' : '?'
        return `  ${key}${optional}: ${tsType(value)}`
      })
      return `{\n${fields.join('\n')}\n}`
    }
    if (schema.additionalProperties === true) return 'Record<string, unknown>'
    if (schema.additionalProperties) return `Record<string, ${tsType(schema.additionalProperties)}>`
    return 'Record<string, unknown>'
  }
  return 'unknown'
}

function describe(schema, indent = '') {
  const description = schema?.description || schema?.title
  return description ? `${indent}/** ${description.replace(/\*\//g, '* /')} */\n` : ''
}

const lines = [
  '// Generated by scripts/gen-api-types.mjs — do not edit by hand.',
  `// Source: ${source}`,
  ''
]

for (const [name, schema] of Object.entries(schemas)) {
  lines.push(describe(schema) + `export interface ${name} {`)
  const required = new Set(schema.required ?? [])
  for (const [key, value] of Object.entries(schema.properties ?? {})) {
    const optional = required.has(key) ? '' : '?'
    lines.push(`${describe(value, '  ')}  ${key}${optional}: ${tsType(value)}`)
  }
  lines.push('}', '')
}

if (Object.keys(schemas).length === 0) {
  lines.push('export {}', '')
}

mkdirSync(dirname(output), { recursive: true })
writeFileSync(output, lines.join('\n'), 'utf8')
console.log(`Wrote ${Object.keys(schemas).length} schema(s) to ${output}`)
